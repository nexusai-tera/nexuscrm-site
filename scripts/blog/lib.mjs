const len = (s) => [...String(s)].length;

// File types a post may link to inside the site. Anything else in the checkout (scripts, JSON,
// workflow files, dotfiles) is not a page and must not be linked even though it exists.
const LINKABLE_EXT = /\.(?:html|xml|txt|pdf|jpe?g|png|webp|gif|svg|avif)$/i;
const FORBIDDEN_PREFIX = ['/scripts/', '/blog/posts/', '/node_modules/', '/audit_marketing/', '/proof/'];

// Checks a root-relative path against the repo.
// Returns null (fine), { error } (never allowed) or { missing } (target not in this build/site).
function checkInternalPath(pathname, ctx) {
  let p;
  try { p = decodeURIComponent(pathname); } catch { return { error: 'bad percent-encoding' }; }
  if (p.includes('\0') || p.includes('\\') || p.split('/').includes('..')) return { error: 'path traversal' };
  if (p.split('/').some((seg) => seg.startsWith('.'))) return { error: 'links to dot-files and dot-folders are not allowed' };
  if (FORBIDDEN_PREFIX.some((pre) => p.startsWith(pre))) return { error: 'links to repo internals are not allowed' };
  if (p === '/blog/' || p === '/blog/index.html' || p === '/blog/feed.xml') return null;
  if (/^\/blog\/[^/]+\/$/.test(p)) return { error: 'blog links use /blog/<slug>.html, not /blog/<slug>/' };
  const bm = /^\/blog\/([^/]+)\.html$/.exec(p);
  if (bm) {
    if (ctx.knownSlugs && ctx.knownSlugs.has(bm[1])) return null;
    if (ctx.extraPages && ctx.extraPages.has(bm[1])) return null;
    return { missing: `no post "${bm[1]}" in this build` };
  }
  let rel = p.replace(/^\/+/, '');
  if (rel === '' || rel.endsWith('/')) rel += 'index.html';
  if (!LINKABLE_EXT.test(rel)) return { error: `links to ${path.extname(rel) || 'extension-less'} files are not allowed; link a page (.html) or a document` };
  if (!ctx.root) return null;
  try {
    if (fs.statSync(path.join(ctx.root, rel)).isFile()) return null;
  } catch { /* missing */ }
  return { missing: `no file ${rel} in the site` };
}

// Classifies one raw href from a post body.
// Returns null (fine), { error: msg } (never allowed) or { missing: msg } (internal target absent).
export function classifyHref(raw, ctx = {}) {
  if (raw == null || raw === '') return { error: 'link without href' };
  const v = cleanHref(raw);
  if (v == null) return { error: `unsafe or malformed href ${JSON.stringify(String(raw).slice(0, 80))}` };
  if (v.startsWith('#')) return null;
  if (/^mailto:/i.test(v)) return v.length > 7 ? null : { error: 'empty mailto:' };
  if (/^tel:/i.test(v)) return /^tel:\+?[0-9().\- ]{3,}$/i.test(v.replace(/%20/g, ' ')) ? null : { error: 'bad tel: number' };
  if (/^http:/i.test(v)) return { error: `use https:// (${v.slice(0, 80)})` };
  const tag = (r) => (r ? (r.error ? { error: `${v.slice(0, 120)}: ${r.error}` } : { missing: `${v.slice(0, 120)}: ${r.missing}` }) : null);
  if (/^https:/i.test(v)) {
    let u;
    try { u = new URL(v); } catch { return { error: `bad URL ${v.slice(0, 80)}` }; }
    if (u.hostname.toLowerCase() === SITE_HOST || u.hostname.toLowerCase() === 'www.' + SITE_HOST) return tag(checkInternalPath(u.pathname, ctx));
    return null;
  }
  if (v.startsWith('/')) return tag(checkInternalPath(v.replace(/[?#].*$/, ''), ctx));
  return { error: `relative links are not allowed (${v.slice(0, 80)}); use /page.html` };
}

// Strict form used for new feed items: a missing internal target is an error too.
// Returns an error string or null.
export function checkPostHref(raw, ctx = {}) {
  const r = classifyHref(raw, ctx);
  return r ? r.error || r.missing : null;
}

// Tag-name checks are plain regexes (linear: no unbounded [^>]* after a "<"). Attribute
// checks run on the tokenizer's output instead, which stays linear on input such as
// "<a " repeated 60,000 times with no ">".
const UNSAFE_BODY = [
  [/<\s*(script|iframe|object|embed|frame|frameset|applet|base|meta|link|form|input|button|textarea|select)\b/i, (m) => `contains <${m[1].toLowerCase()}>`],
];
const WARN_BODY = [
  [/<\s*h1\b/i, 'contains <h1> (rendered as <h2>)'],
  [/<\s*img\b/i, 'contains <img> (removed)'],
  [/<\s*(svg|math|style|noscript|template)\b/i, 'contains markup that is removed'],
];
const URL_ATTRS = new Set(['src', 'action', 'formaction', 'xlink:href']);

// One tokenizer pass over a raw body: every <a href> value and the attribute flags.
function scanBody(html) {
  const hrefs = [];
  const flags = { on: false, src: false, style: false, cls: false };
  for (const tok of tokenize(html)) {
    if (tok.type !== 'start') continue;
    if (tok.name === 'a') {
      const h = firstAttr(tok.attrs, 'href');
      hrefs.push(h === undefined ? null : h);
    }
    for (const a of tok.attrs) {
      if (/^on[a-z]+$/.test(a.name)) flags.on = true;
      else if (URL_ATTRS.has(a.name) && tok.name !== 'img') flags.src = true;
      else if (a.name === 'style') flags.style = true;
      else if (a.name === 'class') flags.cls = true;
    }
  }
  return { hrefs, flags };
}

// Text-field hygiene shared by validatePost: control characters, bidi overrides and HTML
// comment markers (which would break the marker-delimited blocks in llms.txt and sitemap.xml).
function textProblems(v, { multiline = false } = {}) {
  const s = String(v);
  const probs = [];
  const ctl = multiline ? s.replace(/[\t\n\r]/g, ' ') : s.replace(/\t/g, ' ');
  if (CONTROL_RE.test(ctl) || (!multiline && /[\n\r]/.test(s))) probs.push('contains control characters');
  if (BIDI_RE.test(s)) probs.push('contains bidi override characters');
  if (s.includes('<!--') || s.includes('-->')) probs.push('contains an HTML comment marker (<!-- or -->)');
  return probs;
}

// Validates a post against CONTRACTS.md section 2.
// ctx: { pool: Map|{images:Map}, root, knownSlugs:Set, extraPages:Set, fileSlug, now:Date,
//        lenientLinks: bool }
// lenientLinks (build.mjs): a link to a post or site file that does not exist is a warning,
// not an error; the build unwraps such links. sync.mjs leaves it off, so new feed items must
// link only to targets that exist.
// The result carries `clean` (the sanitized body) when the body was sanitized, so callers
// need not sanitize it again.
export function validatePost(post, ctx = {}) {
  const errors = [];
  const warnings = [];
  const err = (f, m) => errors.push(`${f}: ${m}`);
  const warn = (f, m) => warnings.push(`${f}: ${m}`);
  if (!post || typeof post !== 'object' || Array.isArray(post)) return { ok: false, errors: ['post: not a JSON object'], warnings };
  const pool = ctx.pool instanceof Map ? ctx.pool : ctx.pool && ctx.pool.images instanceof Map ? ctx.pool.images : null;

  const reqStr = (f, min, max) => {
    const v = post[f];
    if (typeof v !== 'string' || !v.trim()) { err(f, 'required'); return; }
    const n = len(v.trim());
    if (n < min || n > max) err(f, `${n} characters, must be ${min}-${max}`);
    if (v !== v.trim()) warn(f, 'leading or trailing whitespace');
  };
  const optStr = (f, min, max) => {
    const v = post[f];
    if (v === undefined || v === null || v === '') return;
    if (typeof v !== 'string') { err(f, 'must be a string'); return; }
    const n = len(v.trim());
    if (n < min || n > max) err(f, `${n} characters, must be ${min}-${max}`);
  };

  // slug
  if (typeof post.slug !== 'string') err('slug', 'required');
  else {
    if (!SLUG_RE.test(post.slug)) err('slug', `"${post.slug.slice(0, 90)}" is not kebab-case [a-z0-9-]`);
    if (post.slug.length < 3 || post.slug.length > 80) err('slug', `${post.slug.length} characters, must be 3-80`);
    if (ctx.fileSlug !== undefined && ctx.fileSlug !== post.slug) err('slug', `"${post.slug}" does not match the file name "${ctx.fileSlug}.json"`);
    if (isReservedSlug(post.slug)) err('slug', `"${post.slug}" is reserved (it would collide with a generated blog file)`);
  }
  // text hygiene on every field that reaches the page head, the cards, llms.txt or the feed
  const hygiene = (f, v, opts) => { if (typeof v === 'string') for (const m of textProblems(v, opts)) err(f, m); };
  hygiene('title', post.title);
  hygiene('seo_title', post.seo_title);
  hygiene('description', post.description, { multiline: true });
  hygiene('excerpt', post.excerpt, { multiline: true });
  hygiene('image_alt', post.image_alt);
  hygiene('primary_keyword', post.primary_keyword);
  if (Array.isArray(post.tags)) post.tags.forEach((t) => hygiene('tags', t));
  if (post.author && typeof post.author === 'object') hygiene('author', post.author.name);
  if (Array.isArray(post.faq)) post.faq.forEach((f, k) => { if (f && typeof f === 'object') { hygiene(`faq[${k}].q`, f.q, { multiline: true }); hygiene(`faq[${k}].a`, f.a, { multiline: true }); } });
  reqStr('title', 20, 90);
  optStr('seo_title', 1, 60);
  reqStr('description', 70, 160);
  optStr('excerpt', 80, 260);
  if (!CATEGORIES.includes(post.category)) err('category', `${JSON.stringify(post.category)} is not one of: ${CATEGORIES.join(' | ')}`);

  // tags
  if (!Array.isArray(post.tags)) err('tags', 'required array of 2-6 tags');
  else {
    if (post.tags.length < 2 || post.tags.length > 6) err('tags', `${post.tags.length} tags, must be 2-6`);
    const seen = new Set();
    for (const t of post.tags) {
      if (typeof t !== 'string' || !t.trim() || len(t) > 40) { err('tags', `bad tag ${JSON.stringify(t)}`); continue; }
      if (t !== t.toLowerCase()) err('tags', `"${t}" must be lowercase`);
      if (seen.has(t)) warn('tags', `duplicate "${t}"`);
      seen.add(t);
    }
  }

  // dates
  const today = todayToronto(ctx.now || new Date());
  if (!isValidYmd(post.date)) err('date', `${JSON.stringify(post.date)} is not a valid YYYY-MM-DD date`);
  else if (post.date > addDays(today, 1)) err('date', `${post.date} is more than 1 day in the future (Toronto today is ${today})`);
  if (post.updated !== undefined && post.updated !== null && post.updated !== '') {
    if (!isValidYmd(post.updated)) err('updated', `${JSON.stringify(post.updated)} is not a valid YYYY-MM-DD date`);
    else if (post.updated > addDays(today, 1)) err('updated', `${post.updated} is in the future`);
    else if (isValidYmd(post.date) && post.updated < post.date) warn('updated', 'earlier than date');
  }

  // author
  if (post.author === undefined || post.author === null) warn('author', `missing, "${DEFAULT_AUTHOR}" used`);
  else if (typeof post.author !== 'object' || typeof post.author.name !== 'string' || !post.author.name.trim() || len(post.author.name) > 80) err('author', 'must be { "name": "..." } (1-80 characters)');

  // image
  if (typeof post.image !== 'string' || !post.image) err('image', 'required pool id');
  else if (!pool) err('image', 'image pool not loaded');
  else if (!pool.has(post.image)) err('image', `"${post.image}" is not in img/blog/pool.json`);
  reqStr('image_alt', 10, 160);

  // body
  let clean;
  if (typeof post.body_html !== 'string' || !post.body_html.trim()) err('body_html', 'required');
  else if (post.body_html.length > MAX_BODY_CHARS) err('body_html', `${post.body_html.length} characters, at most ${MAX_BODY_CHARS}`);
  else {
    const body = post.body_html;
    for (const [re, msg] of UNSAFE_BODY) {
      const m = re.exec(body);
      if (m) err('body_html', msg(m));
    }
    for (const [re, msg] of WARN_BODY) if (re.test(body)) warn('body_html', msg);
    if (BIDI_RE.test(body)) err('body_html', 'contains bidi override characters');
    const scan = scanBody(body);
    if (scan.flags.on) err('body_html', 'contains an on* event attribute');
    if (scan.flags.src) err('body_html', 'contains a src/action attribute');
    if (scan.flags.style) warn('body_html', 'contains inline styles (removed)');
    if (scan.flags.cls) warn('body_html', 'contains class attributes (removed)');
    for (const h of scan.hrefs) {
      const r = classifyHref(h, ctx);
      if (!r) continue;
      if (r.error) err('body_html', `link: ${r.error}`);
      else if (ctx.lenientLinks) warn('body_html', `link: ${r.missing}; the link is removed and its text kept`);
      else err('body_html', `link: ${r.missing}`);
    }
    const s = sanitizeBodyChecked(body, MAX_BODY_DEPTH);
    if (s.tooDeep) err('body_html', `elements nested more than ${MAX_BODY_DEPTH} deep`);
    else {
      clean = s.html;
      const words = wordCount(clean);
      if (words < 700 || words > 3500) err('body_html', `${words} words, must be 700-3,500`);
    }
  }

  // faq
  if (post.faq !== undefined && post.faq !== null) {
    if (!Array.isArray(post.faq)) err('faq', 'must be an array');
    else {
      if (post.faq.length > 8) err('faq', `${post.faq.length} items, at most 8`);
      post.faq.forEach((f, k) => {
        if (!f || typeof f !== 'object') { err(`faq[${k}]`, 'must be { q, a }'); return; }
        if (typeof f.q !== 'string' || !f.q.trim() || len(f.q) > 200) err(`faq[${k}].q`, 'required, at most 200 characters');
        if (typeof f.a !== 'string' || !f.a.trim() || len(f.a) > 900) err(`faq[${k}].a`, 'required, at most 900 characters');
        if (/<[A-Za-z!/]/.test(`${f.q} ${f.a}`)) warn(`faq[${k}]`, 'contains markup; it is shown as plain text');
      });
    }
  }

  if (post.social !== undefined && post.social !== null) {
    if (typeof post.social !== 'object' || Array.isArray(post.social)) err('social', 'must be an object');
    else if (post.social.facebook !== undefined && typeof post.social.facebook !== 'string') err('social.facebook', 'must be a string');
  }
  if (post.source !== undefined && !['manual', 'n8n'].includes(post.source)) warn('source', `unexpected value ${JSON.stringify(post.source)}`);
  if (post.primary_keyword !== undefined && post.primary_keyword !== null && typeof post.primary_keyword !== 'string') err('primary_keyword', 'must be a string');

  return { ok: errors.length === 0, errors, warnings, clean };
}

