// Reads img/blog/pool.json. Returns { images: Map(id -> entry), errors: [] }.
export function loadPool(root) {
  const file = path.join(root, 'img', 'blog', 'pool.json');
  const result = { images: new Map(), errors: [], file };
  let data;
  try {
    data = JSON.parse(fs.readFileSync(file, 'utf8'));
  } catch (e) {
    result.errors.push(`pool: cannot read ${path.relative(root, file)}: ${e.message}`);
    return result;
  }
  if (!data || !Array.isArray(data.images)) {
    result.errors.push('pool: "images" must be an array');
    return result;
  }
  for (const img of data.images) {
    if (!img || typeof img.id !== 'string' || !SLUG_RE.test(img.id)) { result.errors.push(`pool: entry with a bad id skipped: ${JSON.stringify(img && img.id)}`); continue; }
    const okPath = (p) => typeof p === 'string' && /^\/img\/blog\/[A-Za-z0-9._-]+$/.test(p);
    if (!okPath(img.src)) { result.errors.push(`pool: ${img.id}: bad src`); continue; }
    if (result.images.has(img.id)) { result.errors.push(`pool: duplicate id ${img.id}`); continue; }
    result.images.set(img.id, {
      ...img,
      card: okPath(img.card) ? img.card : img.src,
      width: Number.isInteger(img.width) ? img.width : 1600,
      height: Number.isInteger(img.height) ? img.height : 840,
      alt: typeof img.alt === 'string' ? img.alt : '',
      // CONTRACTS 7b: true for broll-* and aic-* photos. Inferred from the id when the field is missing.
      ai_generated: typeof img.ai_generated === 'boolean' ? img.ai_generated : /^(broll|aic)-/.test(img.id),
    });
  }
  return result;
}

// Alt text stays a literal description (CONTRACTS 7b): drop an "AI-generated image:" prefix.
export function literalAlt(s) {
  const t = String(s ?? '').trim().replace(/^ai[- ]generated\s+(?:image|illustration|photo|picture)\s*[:\u2013\u2014-]\s*/i, '');
  return t ? t[0].toUpperCase() + t.slice(1) : t;
}

