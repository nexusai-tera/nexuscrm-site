// ---------------------------------------------------------------- escaping

// Text nodes: & < > only. Apostrophes are left alone (the n8n monitor and the h1 rely on it).
// Control characters (other than tab, LF and CR) are dropped.
export function escText(s) {
  return String(s ?? '').replace(/[\u0000-\u0008\u000B\u000C\u000E-\u001F\u007F]/g, '').replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
}
export function escAttr(s) {
  return escText(s).replace(/"/g, '&quot;');
}
// XML text and attributes; also drops characters XML 1.0 forbids.
export function escXml(s) {
  return escAttr(stripXmlInvalid(s));
}
export function stripXmlInvalid(s) {
  return String(s ?? '').replace(/[\u0000-\u0008\u000B\u000C\u000E-\u001F\uFFFE\uFFFF]/g, '');
}
// JSON-LD inside <script>: a "</script>" in post text cannot break out.
export function jsonLd(obj) {
  return JSON.stringify(obj, null, 2).replace(/</g, '\\u003c');
}
// CDATA section that survives a "]]>" in the content.
export function cdata(s) {
  return '<![CDATA[' + stripXmlInvalid(s).replace(/\]\]>/g, ']]]]><![CDATA[>') + ']]>';
}

