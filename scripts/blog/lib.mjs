// Returns the cleaned href, or null when it must not be used.
// The value is decoded first, then every whitespace/control/invisible character is removed
// before the scheme check, so "jav&#x09;ascript:", "&#106;avascript:", " javascript:" and
// "java\nscript:" all fail. The caller escapes every "&" in the result, so the browser sees
// exactly the string that was checked.
export function cleanHref(raw) {
  if (raw == null) return null;
  let v = decodeEntities(raw, true);
  v = v.replace(/^[\u0000- ]+|[\u0000- ]+$/g, '').replace(/[\t\n\r]/g, '');
  const probe = v.replace(/[\u0000- \u007F-\u009F\u00AD\u200B-\u200F\u2028\u2029\u2060\uFEFF]/g, '').toLowerCase();
  if (!probe) return null;
  if (probe.includes('\\')) return null;
  if (probe.startsWith('//')) return null;
  const m = /^([^/?#]*?):/.exec(probe);
  if (m && !ALLOWED_SCHEMES.has(m[1])) return null;
  v = v.replace(/[\u0000-\u001F\u007F]/g, '').replace(/ /g, '%20');
  if (/^https?:/i.test(v)) {
    try { new URL(v); } catch { return null; }
  }
  return v;
}

export function isExternalHref(href) {
  if (!/^https?:/i.test(href)) return false;
  try { return new URL(href).hostname.toLowerCase() !== SITE_HOST; } catch { return true; }
}

function firstAttr(attrs, name) {
  const a = attrs.find((x) => x.name === name);
  return a ? a.value : undefined;
}

function cleanText(v, max = 300) {
  return decodeEntities(v, true).replace(/[\u0000-\u001F\u007F]/g, ' ').replace(/\s+/g, ' ').trim().slice(0, max);
}

// Builds the attribute string for an allowed element, or null if the element must be dropped.
function cleanAttrs(name, attrs) {
  let out = '';
  if (name === 'a') {
    const href = cleanHref(firstAttr(attrs, 'href'));
    if (href == null) return null;
    out += ` href="${escAttr(href)}"`;
    const t = firstAttr(attrs, 'title');
    if (t != null && cleanText(t)) out += ` title="${escAttr(cleanText(t))}"`;
    if (isExternalHref(href)) out += ' rel="noopener"';
    return out;
  }
  if (name === 'th' || name === 'td') {
    for (const k of ['colspan', 'rowspan']) {
      const v = firstAttr(attrs, k);
      if (v != null && /^\s*\d{1,4}\s*$/.test(v)) {
        const num = Math.min(1000, Math.max(1, parseInt(v, 10)));
        out += ` ${k}="${num}"`;
      }
    }
    if (name === 'th') {
      const s = (firstAttr(attrs, 'scope') || '').trim().toLowerCase();
      if (['row', 'col', 'rowgroup', 'colgroup'].includes(s)) out += ` scope="${s}"`;
    }
    return out;
  }
  if (name === 'ol') {
    const v = firstAttr(attrs, 'start');
    if (v != null && /^\s*-?\d{1,6}\s*$/.test(v)) out += ` start="${parseInt(v, 10)}"`;
    return out;
  }
  if (name === 'abbr') {
    const t = firstAttr(attrs, 'title');
    if (t != null && cleanText(t)) out += ` title="${escAttr(cleanText(t))}"`;
    return out;
  }
  return out;
}

// Text: < and > escaped, a bare & escaped, well-formed character references kept.
function cleanTextNode(t) {
  return t
    .replace(/[\u0000-\u0008\u000B\u000C\u000E-\u001F\u007F]/g, '')
    .replace(/&(?!(?:#\d{1,7}|#[xX][0-9a-fA-F]{1,6}|[A-Za-z][A-Za-z0-9]{0,31});)/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;');
}

// Strict allowlist sanitizer for post bodies. Output is canonical: lower-case allowed tags,
// only allowlisted attributes (double-quoted, escaped), every element closed in stack order.
export function sanitizeBody(html) {
  return sanitizeBodyChecked(html).html;
}

// Same as sanitizeBody, but stops early when the open-element stack would grow past maxDepth
// (returns { html: null, tooDeep: true }). Returns { html, tooDeep: false, depth } otherwise.
export function sanitizeBodyChecked(html, maxDepth = Infinity) {
  const out = [];
  const stack = [];
  let depth = 0;
  let drop = null;
  const closeTo = (idx) => { while (stack.length > idx) out.push(`</${stack.pop()}>`); };
  // close the nearest open element in `targets`, walking down past `pass` elements only
  const closeNearest = (targets, pass) => {
    for (let k = stack.length - 1; k >= 0; k--) {
      const el = stack[k];
      if (targets.has(el)) { closeTo(k); return; }
      if (!pass.has(el)) return;
    }
  };
  const closeP = () => {
    for (let k = stack.length - 1; k >= 0; k--) {
      if (stack[k] === 'p') { closeTo(k); return; }
      if (SCOPE_STOP.has(stack[k])) return;
    }
  };
  for (const tok of tokenize(html)) {
    if (drop) {
      if (tok.type === 'start' && tok.name === drop.name && !(tok.selfClosing && SELF_CLOSING_FOREIGN.has(tok.name))) drop.depth++;
      else if (tok.type === 'end' && tok.name === drop.name && --drop.depth === 0) drop = null;
      continue;
    }
    if (tok.type === 'text') { out.push(cleanTextNode(tok.text)); continue; }
    if (tok.type === 'start') {
      if (tok.raw) continue; // raw-text element: its content is already gone
      if (DROP_VOID.has(tok.name)) continue;
      if (DROP_CONTENT.has(tok.name)) {
        if (!(tok.selfClosing && SELF_CLOSING_FOREIGN.has(tok.name))) drop = { name: tok.name, depth: 1 };
        continue;
      }
      const name = ALIAS[tok.name] || tok.name;
      if (!ALLOWED_TAGS.has(name)) continue;
      const attrs = cleanAttrs(name, tok.attrs);
      if (attrs === null) continue;
      if (BLOCKS.has(name)) closeP();
      if (HEADINGS.has(name)) {
        const k = lastIndexWhere(stack, (e) => HEADINGS.has(e));
        if (k !== -1) closeTo(k);
      }
      if (name === 'li') closeNearest(new Set(['li']), new Set([...INLINE, 'p']));
      if (name === 'dt' || name === 'dd') closeNearest(new Set(['dt', 'dd']), new Set([...INLINE, 'p']));
      if (name === 'td' || name === 'th') closeNearest(new Set(['td', 'th']), new Set([...INLINE, ...BLOCKS, 'li', 'ul', 'ol', 'dl', 'dt', 'dd', 'br']));
      if (name === 'tr') closeNearest(new Set(['tr']), new Set([...INLINE, ...BLOCKS, 'td', 'th', 'li', 'dt', 'dd']));
      if (name === 'thead' || name === 'tbody') closeNearest(new Set(['thead', 'tbody']), new Set([...INLINE, ...BLOCKS, 'tr', 'td', 'th', 'li', 'dt', 'dd']));
      if (name === 'a') {
        const k = stack.lastIndexOf('a');
        if (k !== -1) closeTo(k);
      }
      out.push(`<${name}${attrs}>`);
      if (!VOID.has(name)) {
        stack.push(name);
        if (stack.length > depth) depth = stack.length;
        if (depth > maxDepth) return { html: null, tooDeep: true, depth };
      }
      continue;
    }
    if (tok.type === 'end') {
      const name = ALIAS[tok.name] || tok.name;
      if (!ALLOWED_TAGS.has(name) || VOID.has(name)) continue;
      let k = stack.lastIndexOf(name);
      if (k === -1 && HEADINGS.has(name)) k = lastIndexWhere(stack, (e) => HEADINGS.has(e));
      if (k !== -1) closeTo(k);
    }
  }
  closeTo(0);
  return { html: out.join(''), tooDeep: false, depth };
}

function lastIndexWhere(arr, fn) {
  for (let k = arr.length - 1; k >= 0; k--) if (fn(arr[k])) return k;
  return -1;
}

// ---------------------------------------------------------------- text, ids, body transforms

export function plainText(html) {
  return decodeEntities(String(html ?? '').replace(/<[^>]*>/g, ' ')).replace(/\s+/g, ' ').trim();
}
export function wordCount(html) {
  const t = plainText(html);
  return t ? t.split(/\s+/).length : 0;
}
export function readingMinutes(words) {
  return Math.max(1, Math.ceil(words / 230));
}

export function slugifyHeading(text) {
  let s = String(text ?? '').normalize('NFKD').replace(/[\u0300-\u036F]/g, '').toLowerCase().replace(/&/g, ' and ');
  s = s.replace(/[^a-z0-9 -]/g, '').trim().replace(/\s+/g, '-').replace(/-+/g, '-').replace(/^-|-$/g, '');
  s = s.slice(0, 60).replace(/-+$/g, '');
  return s || 'section';
}

const TAG_RE = /<(\/?)([a-z][a-z0-9]*)\b[^>]*>/g;
const NO_CLOSE = new Set(['br', 'hr']);
// Offsets of the <h2> start tags that sit at the top level of canonical (sanitized) HTML,
// i.e. not inside a list item, blockquote, table cell or any other element.
export function topLevelH2Offsets(html) {
  const s = String(html);
  const list = [];
  let depth = 0;
  TAG_RE.lastIndex = 0;
  let m;
  while ((m = TAG_RE.exec(s))) {
    const name = m[2];
    if (NO_CLOSE.has(name)) continue;
    if (m[1]) { depth = Math.max(0, depth - 1); continue; }
    if (name === 'h2' && depth === 0) list.push(m.index);
    depth++;
  }
  return list;
}

// Adds ids to every <h2> and <h3> of sanitized HTML. Returns the html and the headings;
// `top` marks the <h2>s at the top level of the body (the ones the TOC lists).
export function addHeadingIds(html, reserved = RESERVED_IDS) {
  const used = new Set(reserved);
  const headings = [];
  const src = String(html);
  const top = new Set(topLevelH2Offsets(src));
  const out = src.replace(/<(h[23])>([\s\S]*?)<\/\1>/g, (m, tag, inner, off) => {
    const text = plainText(inner);
    const base = slugifyHeading(text);
    let id = base;
    for (let k = 2; used.has(id); k++) id = `${base}-${k}`;
    used.add(id);
    headings.push({ level: Number(tag[1]), id, text, top: tag === 'h2' && top.has(off) });
    return `<${tag} id="${id}">${inner}</${tag}>`;
  });
  return { html: out, headings };
}

// Wraps each table for sideways scrolling and gives it the site table style.
export function wrapTables(html) {
  return String(html)
    .replace(/<table>(\s*<caption>([\s\S]*?)<\/caption>)?/g, (m, cap, capInner) => {
      const label = (cap ? plainText(capInner) : '').slice(0, 120) || 'Table';
      // the hint is shown by the post page script only while the table is wider than its box
      return `<p class="tbl-hint" aria-hidden="true" hidden>Swipe the table sideways to see every column.</p><div class="tbl-scroll wide" role="region" tabindex="0" aria-label="${escAttr(label)}"><table class="cmp">${cap || ''}`;
    })
    .replace(/<\/table>/g, '</table></div>');
}

// Inserts `block` before the 3rd top-level <h2> (after the 2nd h2's section) when there are
// 3 or more. h2s nested in a list, quote or table do not count, so the block never lands
// inside one of those.
export function insertBeforeThirdH2(html, block) {
  const s = String(html);
  const at = topLevelH2Offsets(s);
  if (at.length < 3) return s;
  return s.slice(0, at[2]) + block + '\n' + s.slice(at[2]);
}

// Unwraps internal links whose target will not exist on the live site: /blog/<slug>.html for a
// slug not in `liveSlugs`, or a root-relative / own-domain path with no file in the repo.
// The link text stays; only the <a> goes. Works on sanitized HTML (canonical <a href="...">).
// Returns { html, unlinked: [href, ...] }.
export function unlinkMissingInternal(html, { root, liveSlugs = new Set() } = {}) {
  const unlinked = [];
  const out = String(html).replace(/<a href="([^"]*)"[^>]*>([\s\S]*?)<\/a>/g, (m, rawHref, inner) => {
    const href = decodeEntities(rawHref, true);
    const r = classifyHref(href, { root, knownSlugs: liveSlugs });
    if (r && r.missing) { unlinked.push(href); return inner; }
    return m;
  });
  return { html: out, unlinked };
}

// Root-relative hrefs become absolute (for the RSS content:encoded copy).
export function absolutizeLinks(html) {
  return String(html).replace(/ href="\/(?!\/)/g, ` href="${SITE}/`);
}

// ---------------------------------------------------------------- dates

export function isValidYmd(s) {
  if (typeof s !== 'string' || !/^\d{4}-\d{2}-\d{2}$/.test(s)) return false;
  const [y, m, d] = s.split('-').map(Number);
  const dt = new Date(Date.UTC(y, m - 1, d));
  return dt.getUTCFullYear() === y && dt.getUTCMonth() === m - 1 && dt.getUTCDate() === d;
}
export function addDays(ymd, n) {
  const [y, m, d] = ymd.split('-').map(Number);
  const dt = new Date(Date.UTC(y, m - 1, d + n));
  return dt.toISOString().slice(0, 10);
}
export function todayToronto(now = new Date()) {
  const parts = new Intl.DateTimeFormat('en-CA', { timeZone: 'America/Toronto', year: 'numeric', month: '2-digit', day: '2-digit' }).formatToParts(now);
  const get = (t) => parts.find((p) => p.type === t).value;
  return `${get('year')}-${get('month')}-${get('day')}`;
}
// "Nov 17, 2026", from a fixed month table (no locale data involved).
export function formatDateDisplay(ymd) {
  const [y, m, d] = ymd.split('-').map(Number);
  return `${MONTHS[m - 1]} ${d}, ${y}`;
}
function nthSunday(y, month, n) {
  const first = new Date(Date.UTC(y, month - 1, 1)).getUTCDay();
  return 1 + ((7 - first) % 7) + 7 * (n - 1);
}
// UTC offset of America/Toronto at 00:00 local on that date (rules in force since 2007:
// EDT from the 2nd Sunday of March 02:00 to the 1st Sunday of November 02:00).
export function torontoMidnightOffset(ymd) {
  const [y, m, d] = ymd.split('-').map(Number);
  const md = m * 100 + d;
  const start = 300 + nthSunday(y, 3, 2);
  const end = 1100 + nthSunday(y, 11, 1);
  return md > start && md <= end ? '-0400' : '-0500';
}
// ISO 8601 local midnight in Toronto with its offset, e.g. 2026-11-11T00:00:00-05:00 (the same
// instant as the RSS pubDate).
export function isoMidnight(ymd) {
  const off = torontoMidnightOffset(ymd);
  return `${ymd}T00:00:00${off.slice(0, 3)}:${off.slice(3)}`;
}
export function rfc822Midnight(ymd) {
  const [y, m, d] = ymd.split('-').map(Number);
  const dow = new Date(Date.UTC(y, m - 1, d)).getUTCDay();
  return `${DOW[dow]}, ${String(d).padStart(2, '0')} ${MONTHS[m - 1]} ${y} 00:00:00 ${torontoMidnightOffset(ymd)}`;
}

