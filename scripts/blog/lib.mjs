export function writeIfChanged(file, content) {
  try {
    if (fs.readFileSync(file, 'utf8') === content) return false;
  } catch { /* new file */ }
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, content);
  return true;
}

export function annotate(level, message, file) {
  // GitHub Actions annotations when running in CI, plain lines otherwise
  if (process.env.GITHUB_ACTIONS === 'true') {
    const clean = String(message).replace(/%/g, '%25').replace(/\r/g, '%0D').replace(/\n/g, '%0A');
    console.log(`::${level}${file ? ` file=${file}` : ''}::${clean}`);
  } else {
    (level === 'error' ? console.error : console.log)(`${level.toUpperCase()}${file ? ` ${file}` : ''}: ${message}`);
  }
}
