function codePoint(n) {
  if (!Number.isFinite(n) || n === 0 || n > 0x10ffff || (n >= 0xd800 && n <= 0xdfff)) return '\uFFFD';
  return String.fromCodePoint(n);
}

// Decodes character references the way a browser would (numeric with or without ';',
// named from the table above). Unknown names are left as written.
export function decodeEntities(s, inAttribute = false) {
  return String(s ?? '').replace(/&(#[xX][0-9a-fA-F]+;?|#\d+;?|[A-Za-z][A-Za-z0-9]*;?)/g, (m, body, off, str) => {
    if (body[0] === '#') {
      const hex = body[1] === 'x' || body[1] === 'X';
      const digits = body.slice(hex ? 2 : 1).replace(/;$/, '');
      return codePoint(parseInt(digits, hex ? 16 : 10));
    }
    const semi = body.endsWith(';');
    const name = semi ? body.slice(0, -1) : body;
    if (semi && Object.prototype.hasOwnProperty.call(NAMED, name)) return NAMED[name];
    if (!semi && LEGACY.has(name)) {
      const next = str[off + m.length] || '';
      if (inAttribute && /[A-Za-z0-9=]/.test(next)) return m;
      return NAMED[name];
    }
    return m;
  });
}

// ---------------------------------------------------------------- tokenizer

const WS = /[\t\n\f\r ]/;
// Elements whose content the HTML tokenizer reads as raw text up to the matching end tag.
const RAWTEXT = new Set(['script', 'style', 'iframe', 'noscript', 'xmp', 'noembed', 'noframes', 'textarea', 'title']);

function readAttrs(html, i, n) {
  // returns { attrs, selfClosing, end } where end is the index after '>' or -1 at EOF
  const attrs = [];
  let selfClosing = false;
  while (i < n) {
    const c = html[i];
    if (WS.test(c)) { i++; continue; }
    if (c === '/') { selfClosing = html[i + 1] === '>'; i++; continue; }
    if (c === '>') return { attrs, selfClosing, end: i + 1 };
    selfClosing = false;
    let j = i + 1;
    while (j < n && !WS.test(html[j]) && html[j] !== '/' && html[j] !== '>' && html[j] !== '=') j++;
    const name = html.slice(i, j).toLowerCase();
    i = j;
    while (i < n && WS.test(html[i])) i++;
    let value = '';
    if (html[i] === '=') {
      i++;
      while (i < n && WS.test(html[i])) i++;
      const q = html[i];
      if (q === '"' || q === "'") {
        const close = html.indexOf(q, i + 1);
        if (close === -1) return { attrs, selfClosing: false, end: -1 };
        value = html.slice(i + 1, close);
        i = close + 1;
      } else {
        let k = i;
        while (k < n && !WS.test(html[k]) && html[k] !== '>') k++;
        value = html.slice(i, k);
        i = k;
      }
    }
    attrs.push({ name, value });
  }
  return { attrs, selfClosing: false, end: -1 };
}

// Yields {type:'text', text} | {type:'start', name, attrs, selfClosing} | {type:'end', name}.
// Comments, doctypes and processing instructions are swallowed. A tag cut off by the end of
// the input is dropped, as browsers do. Raw-text elements swallow their content.
export function* tokenize(input) {
  const html = String(input ?? '');
  const n = html.length;
  let i = 0;
  while (i < n) {
    const lt = html.indexOf('<', i);
    if (lt === -1) { yield { type: 'text', text: html.slice(i) }; return; }
    if (lt > i) yield { type: 'text', text: html.slice(i, lt) };
    i = lt;
    const c = html[i + 1];
    if (html.startsWith('<!--', i)) {
      if (html.startsWith('<!-->', i)) { i += 5; continue; }
      if (html.startsWith('<!--->', i)) { i += 6; continue; }
      const a = html.indexOf('-->', i + 4);
      const b = html.indexOf('--!>', i + 4);
      if (a === -1 && b === -1) return;
      if (b !== -1 && (a === -1 || b < a)) i = b + 4; else i = a + 3;
      continue;
    }
    if (c === '!' || c === '?') {
      const gt = html.indexOf('>', i + 2);
      if (gt === -1) return;
      i = gt + 1;
      continue;
    }
    if (c === '/') {
      const d = html[i + 2];
      if (d === '>') { i += 3; continue; }
      if (!d || !/[A-Za-z]/.test(d)) {
        const gt = html.indexOf('>', i + 2);
        if (gt === -1) return;
        i = gt + 1;
        continue;
      }
      let j = i + 2;
      while (j < n && !WS.test(html[j]) && html[j] !== '/' && html[j] !== '>') j++;
      const name = html.slice(i + 2, j).toLowerCase();
      const r = readAttrs(html, j, n);
      if (r.end === -1) return;
      i = r.end;
      yield { type: 'end', name };
      continue;
    }
    if (c && /[A-Za-z]/.test(c)) {
      let j = i + 1;
      while (j < n && !WS.test(html[j]) && html[j] !== '/' && html[j] !== '>') j++;
      const name = html.slice(i + 1, j).toLowerCase();
      const r = readAttrs(html, j, n);
      if (r.end === -1) return;
      i = r.end;
      if (name === 'plaintext') return;
      if (RAWTEXT.has(name)) {
        const re = new RegExp('</' + name + '[\\t\\n\\f\\r />]', 'ig');
        re.lastIndex = i;
        const m = re.exec(html);
        if (!m) { yield { type: 'start', name, attrs: r.attrs, selfClosing: false, raw: true }; return; }
        const close = readAttrs(html, m.index + 2 + name.length, n);
        yield { type: 'start', name, attrs: r.attrs, selfClosing: false, raw: true };
        if (close.end === -1) return;
        i = close.end;
        continue;
      }
      yield { type: 'start', name, attrs: r.attrs, selfClosing: r.selfClosing };
      continue;
    }
    // a "<" that does not open a tag is text
    yield { type: 'text', text: '<' };
    i += 1;
  }
}

