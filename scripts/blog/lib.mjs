export function isRelativeRef(v) {
  return v !== '' && !/^(?:[A-Za-z][A-Za-z0-9+.-]*:|#|\/)/.test(v);
}
// Prefixes every relative href/src with `prefix` (e.g. "../" for pages in /blog/).
export function prefixLinks(html, prefix) {
  return String(html).replace(/(\s(?:href|src))=(["'])(.*?)\2/g, (m, attr, q, v) => (isRelativeRef(v) ? `${attr}=${q}${prefix}${v}${q}` : m));
}

// Takes the nav, footer and Cloudflare beacon line from index.html and rewrites them for
// pages one folder deep. Blog is marked as the current page in the nav.
export function extractChrome(indexHtml, prefix = '../') {
  const errors = [];
  const navM = /<nav class="nav"[^>]*>[\s\S]*?<\/nav>/.exec(indexHtml);
  const footM = /<footer class="site">[\s\S]*?<\/footer>/.exec(indexHtml);
  if (!navM) errors.push('index.html: <nav class="nav"> not found');
  if (!footM) errors.push('index.html: <footer class="site"> not found');
  const beacon = String(indexHtml).split('\n').filter((l) => l.includes('static.cloudflareinsights.com/beacon.min.js'));
  if (beacon.length !== 1) errors.push(`index.html: expected one Cloudflare beacon line, found ${beacon.length}`);
  let nav = navM ? prefixLinks(navM[0], prefix) : '';
  let footer = footM ? prefixLinks(footM[0], prefix) : '';
  const blogHref = `${prefix}blog/`;
  nav = nav.replace(/\s+aria-current="page"/g, '');
  if (!nav.includes(`href="${blogHref}"`)) {
    // index.html without the Blog link yet: add it before the nav button
    nav = nav.replace(/(\n?)(\s*)(<a href="[^"]*" class="btn btn-solid">)/, `$1$2<a href="${blogHref}">Blog</a>$1$2$3`);
  }
  nav = nav.replace(`<a href="${blogHref}">`, `<a href="${blogHref}" aria-current="page">`);
  if (footer && !footer.includes(`href="${blogHref}"`)) {
    footer = footer.replace(/(\n?)(\s*)(<li><a href="[^"]*faq\.html">FAQ<\/a><\/li>)/, `$1$2$3$1$2<li><a href="${blogHref}">Blog</a></li>`);
  }
  // the accountants edition is being taken out of the menus (truth sheet sections 1 and 14)
  footer = footer.replace(/\n?[ \t]*<li><a href="[^"]*industries\/accountants\.html">[^<]*<\/a><\/li>/g, '');
  const ids = [...`${nav}\n${footer}`.matchAll(/\sid=(["'])([^"']+)\1/g)].map((m) => m[2]);
  return { nav, footer, beacon: beacon.length === 1 ? beacon[0].trim() : '', errors, ids };
}

